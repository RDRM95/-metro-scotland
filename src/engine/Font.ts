export const FONT_5x7: BitmapFont = { w: 5, h: 7, glyphs: G7, upperOnly: false };
export const FONT_3x5: BitmapFont = { w: 3, h: 5, glyphs: G5, upperOnly: true };

function normalise(text: string, font: BitmapFont): string {
  let t = text.replace(/’|‘/g, "'").replace(/“|”/g, '"').replace(/–|—/g, '-');
  if (font.upperOnly) t = t.toUpperCase();
  return t;
}

export function measureText(text: string, font: BitmapFont, spacing = 1): number {
  const t = normalise(text, font);
  if (t.length === 0) return 0;
  return t.length * (font.w + spacing) - spacing;
}

export interface TextOpts {
  spacing?: number;
  /** 'left' | 'center' | 'right' */
  align?: 'left' | 'center' | 'right';
  /** Optional 1px drop shadow colour. */
  shadow?: string;
  /** Optional alpha. */
  alpha?: number;
}

export function drawText(ctx: Ctx2D, text: string, x: number, y: number, font: BitmapFont, color: string, opts: TextOpts = {}): number {
  const spacing = opts.spacing ?? 1;
  const t = normalise(text, font);
  const width = measureText(t, font, spacing);
  let cx = x | 0;
  if (opts.align === 'center') cx = Math.round(x - width / 2);
  else if (opts.align === 'right') cx = Math.round(x - width);
  const cy = y | 0;
  const prevAlpha = ctx.globalAlpha;
  if (opts.alpha !== undefined) ctx.globalAlpha = prevAlpha * opts.alpha;

  const draw = (dx: number, dy: number, col: string) => {
    ctx.fillStyle = col;
    let gx = cx + dx;
    for (let i = 0; i < t.length; i++) {
      const ch = t[i];
      const glyph = font.glyphs[ch] ?? font.glyphs['?'];
      for (let r = 0; r < font.h; r++) {
        const row = glyph[r];
        for (let c = 0; c < font.w; c++) {
          if (row[c] === '#') ctx.fillRect(gx + c, cy + dy + r, 1, 1);
        }
      }
      gx += font.w + spacing;
    }
  };
  if (opts.shadow) draw(1, 1, opts.shadow);
  draw(0, 0, color);
  ctx.globalAlpha = prevAlpha;
  return width;
}

/** Draws text with each font pixel enlarged to `scale`×`scale` (for titles). */
export function drawTextScaled(ctx: Ctx2D, text: string, x: number, y: number, font: BitmapFont, scale: number, color: string, opts: TextOpts = {}): number {
  const spacing = opts.spacing ?? 1;
  const t = normalise(text, font);
  const width = measureText(t, font, spacing) * scale;
  let cx = x | 0;
  if (opts.align === 'center') cx = Math.round(x - width / 2);
  else if (opts.align === 'right') cx = Math.round(x - width);
  const cy = y | 0;
  const prevAlpha = ctx.globalAlpha;
  if (opts.alpha !== undefined) ctx.globalAlpha = prevAlpha * opts.alpha;
  const draw = (dx: number, dy: number, col: string) => {
    ctx.fillStyle = col;
    let gx = cx + dx;
    for (let i = 0; i < t.length; i++) {
      const glyph = font.glyphs[t[i]] ?? font.glyphs['?'];
      for (let r = 0; r < font.h; r++) {
        for (let c = 0; c < font.w; c++) {
          if (glyph[r][c] === '#') ctx.fillRect(gx + c * scale, cy + dy + r * scale, scale, scale);
        }
      }
      gx += (font.w + spacing) * scale;
    }
  };
  if (opts.shadow) draw(scale, scale, opts.shadow);
  draw(0, 0, color);
  ctx.globalAlpha = prevAlpha;
  return width;
}

/** Word-wraps text to a max pixel width. */
export function wrapText(text: string, font: BitmapFont, maxWidth: number, spacing = 1): string[] {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let cur = '';
  for (const w of words) {
    const candidate = cur ? `${cur} ${w}` : w;
    if (measureText(candidate, font, spacing) <= maxWidth || !cur) cur = candidate;
    else {
      lines.push(cur);
      cur = w;
    }
  }
  if (cur) lines.push(cur);
  return lines;
}
